    /// Record delivery (idempotent: a second success is a no-op).
    pub async fn de_outbox_mark(
        &self,
        consumer: &str,
        event_id: Uuid,
        ok: bool,
        error_code: Option<&str>,
        retry_in: Duration,
    ) -> Result<(), StorageError> {
        sqlx::query(
            "INSERT INTO solprint.de_outbox_deliveries (consumer, event_id, status, last_error_code, next_attempt_at, delivered_at)
             VALUES ($1, $2, CASE WHEN $3 THEN 'DELIVERED' ELSE 'FAILED' END, $4,
                     CASE WHEN $3 THEN NULL ELSE now() + make_interval(secs => $5::float8 / 1000) END,
                     CASE WHEN $3 THEN now() END)
             ON CONFLICT (consumer, event_id) DO UPDATE SET
                status = CASE WHEN solprint.de_outbox_deliveries.status = 'DELIVERED' THEN 'DELIVERED' ELSE EXCLUDED.status END,
                attempts = solprint.de_outbox_deliveries.attempts + CASE WHEN solprint.de_outbox_deliveries.status = 'DELIVERED' THEN 0 ELSE 1 END,
                last_error_code = EXCLUDED.last_error_code,
                next_attempt_at = CASE WHEN solprint.de_outbox_deliveries.status = 'DELIVERED' THEN NULL ELSE EXCLUDED.next_attempt_at END,
                delivered_at = COALESCE(solprint.de_outbox_deliveries.delivered_at, EXCLUDED.delivered_at),
                updated_at = now()",
        )
        .bind(consumer)
        .bind(event_id)
        .bind(ok)
        .bind(error_code)
        .bind(millis(retry_in))
        .execute(self.pool())
        .await
        .map_err(|x| e(&x))?;
        Ok(())
    }

