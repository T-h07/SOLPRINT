    /// Apply a finality transition guarded by the expected current state.
    /// `ORPHANED` retracts the transaction's swaps and activities. Each
    /// outbox event's `aggregate_revision` is set to the transaction's
    /// current revision inside the same database transaction.
    #[allow(clippy::too_many_arguments)]
    pub async fn de_apply_finality(
        &self,
        signature: &str,
        expected: &str,
        new: &str,
        next_check: Option<&UtcTimestamp>,
        outbox: &[OutboxWrite],
        issue: Option<&IssueWrite>,
    ) -> Result<bool, StorageError> {
        if finality_rank(new) < finality_rank(expected) && new != "ORPHANED" {
            return Ok(false);
        }
        let mut tx = self.pool().begin().await.map_err(|x| e(&x))?;
        let r = sqlx::query(
            "UPDATE solprint.de_transactions
                SET finality = $4, finality_checks = finality_checks + 1,
                    next_finality_check_at = $5,
                    finalized_at = CASE WHEN $4 = 'FINALIZED' THEN COALESCE(finalized_at, now()) ELSE finalized_at END,
                    updated_at = now()
              WHERE network = $1 AND signature = $2 AND finality = $3
             RETURNING current_revision",
        )
        .bind(NETWORK)
        .bind(signature)
        .bind(expected)
        .bind(new)
        .bind(next_check.map(ts))
        .fetch_optional(&mut *tx)
        .await
        .map_err(|x| e(&x))?;
        let Some(r) = r else {
            return Ok(false);
        };
        // Finality events belong to the transaction's current revision; the
        // caller cannot know it without a racy read, so it is stamped here.
        let revision: i32 = r.get("current_revision");
        if new == "ORPHANED" {
            sqlx::query("UPDATE solprint.de_swaps SET finality = 'ORPHANED', canonical = FALSE, retracted_at = now(), retraction_reason = 'ORPHANED' WHERE network = $1 AND signature = $2 AND canonical")
                .bind(NETWORK)
                .bind(signature)
                .execute(&mut *tx)
                .await
                .map_err(|x| e(&x))?;
            sqlx::query("UPDATE solprint.de_activities SET canonical = FALSE, updated_at = now() WHERE network = $1 AND signature = $2")
                .bind(NETWORK)
                .bind(signature)
                .execute(&mut *tx)
                .await
                .map_err(|x| e(&x))?;
            sqlx::query("UPDATE solprint.de_evidence SET canonical = FALSE, superseded_reason = 'ORPHANED' WHERE network = $1 AND signature = $2 AND canonical")
                .bind(NETWORK)
                .bind(signature)
                .execute(&mut *tx)
                .await
                .map_err(|x| e(&x))?;
        } else {
            sqlx::query(
                "UPDATE solprint.de_swaps SET finality = $3,
                        finalized_at = CASE WHEN $3 = 'FINALIZED' THEN COALESCE(finalized_at, now()) ELSE finalized_at END
                  WHERE network = $1 AND signature = $2 AND canonical",
            )
            .bind(NETWORK)
            .bind(signature)
            .bind(new)
            .execute(&mut *tx)
            .await
            .map_err(|x| e(&x))?;
        }
        for o in outbox {
            let mut o = o.clone();
            o.aggregate_revision = revision;
            insert_outbox(&mut tx, &o).await?;
        }
        if let Some(i) = issue {
            insert_issue(&mut tx, i).await?;
        }
        tx.commit().await.map_err(|x| e(&x))?;
        Ok(true)
    }

