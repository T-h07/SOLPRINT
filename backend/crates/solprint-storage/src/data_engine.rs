    /// Prune raw evidence of finalized/orphaned transactions, terminal jobs
    /// and fully delivered outbox events older than the given ages. Hashes,
    /// normalized records and open issues are kept.
    pub async fn de_retention(
        &self,
        evidence_days: u32,
        job_days: u32,
        outbox_days: u32,
        consumers: &[String],
    ) -> Result<RetentionOutcome, StorageError> {
        let mut out = RetentionOutcome::default();
        if evidence_days > 0 {
            out.evidence_pruned = sqlx::query(
                "UPDATE solprint.de_evidence ev SET raw_json = NULL, pruned_at = now()
                  FROM solprint.de_transactions t
                 WHERE ev.network = t.network AND ev.signature = t.signature AND ev.raw_json IS NOT NULL
                   AND t.finality IN ('FINALIZED', 'ORPHANED')
                   AND ev.fetched_at < now() - make_interval(days => $1)",
            )
            .bind(i32::try_from(evidence_days).unwrap_or(i32::MAX))
            .execute(self.pool())
            .await
            .map_err(|x| e(&x))?
            .rows_affected();
        }
        out.jobs_deleted = sqlx::query(
            "DELETE FROM solprint.de_jobs WHERE state IN ('COMPLETED', 'CANCELLED')
               AND completed_at < now() - make_interval(days => $1)",
        )
        .bind(i32::try_from(job_days).unwrap_or(i32::MAX))
        .execute(self.pool())
        .await
        .map_err(|x| e(&x))?
        .rows_affected();
        out.outbox_deleted = sqlx::query(
            "DELETE FROM solprint.de_outbox o
              WHERE o.persisted_at < now() - make_interval(days => $1)
                AND (SELECT count(*) FROM solprint.de_outbox_deliveries d
                      WHERE d.event_id = o.event_id AND d.status = 'DELIVERED' AND d.consumer = ANY($2)) = cardinality($2)",
        )
        .bind(i32::try_from(outbox_days).unwrap_or(i32::MAX))
        .bind(consumers)
        .execute(self.pool())
        .await
        .map_err(|x| e(&x))?
        .rows_affected();
        out.issues_deleted = sqlx::query(
            "DELETE FROM solprint.de_quality_issues WHERE resolved_at IS NOT NULL
               AND resolved_at < now() - make_interval(days => $1)",
        )
        .bind(i32::try_from(job_days).unwrap_or(i32::MAX))
        .execute(self.pool())
        .await
        .map_err(|x| e(&x))?
        .rows_affected();
        Ok(out)
    }

