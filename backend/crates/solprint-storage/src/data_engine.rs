    pub async fn de_counts(&self) -> Result<DeCounts, StorageError> {
        let pairs = |sql: &'static str| async move {
            sqlx::query(sql)
                .fetch_all(self.pool())
                .await
                .map_err(|x| e(&x))
                .map(|rows| {
                    rows.iter()
                        .map(|r| (r.get::<String, _>(0), r.get::<i64, _>(1)))
                        .collect::<Vec<_>>()
                })
        };
        let jobs_by_state =
            pairs("SELECT state, count(*) FROM solprint.de_jobs GROUP BY state ORDER BY state")
                .await?;
        let transactions_by_finality = pairs("SELECT finality, count(*) FROM solprint.de_transactions GROUP BY finality ORDER BY finality").await?;
        let transactions_by_status = pairs("SELECT decode_status, count(*) FROM solprint.de_transactions GROUP BY decode_status ORDER BY decode_status").await?;
        let swaps_by_protocol = pairs("SELECT protocol, count(*) FROM solprint.de_swaps WHERE canonical GROUP BY protocol ORDER BY protocol").await?;
        let open_issues_by_severity = pairs("SELECT severity, count(*) FROM solprint.de_quality_issues WHERE resolved_at IS NULL GROUP BY severity ORDER BY severity").await?;
        let r = sqlx::query(
            "SELECT
                (SELECT min(created_at) FROM solprint.de_jobs WHERE state IN ('PENDING', 'FETCH_RETRY')) AS oldest_pending,
                (SELECT count(*) FROM solprint.de_transactions) AS txs,
                (SELECT count(*) FROM solprint.de_swaps WHERE canonical) AS swaps_canonical,
                (SELECT count(*) FROM solprint.de_swaps WHERE canonical AND classification_status = 'VERIFIED'
                    AND attribution IN ('VERIFIED_OWNER', 'VERIFIED_AUTHORITY', 'VERIFIED_BENEFICIARY')) AS swaps_verified,
                (SELECT count(*) FROM solprint.de_swaps WHERE NOT canonical) AS swaps_retracted,
                (SELECT count(*) FROM solprint.de_outbox) AS outbox_events,
                (SELECT count(*) FROM solprint.de_outbox o WHERE NOT EXISTS (
                    SELECT 1 FROM solprint.de_outbox_deliveries d WHERE d.event_id = o.event_id AND d.status = 'DELIVERED')) AS outbox_undelivered,
                (SELECT count(*) FROM solprint.de_targets WHERE enabled) AS targets_enabled,
                (SELECT count(*) FROM solprint.de_targets) AS targets_total,
                (SELECT count(*) FROM solprint.de_backfills WHERE status IN ('PENDING', 'RUNNING', 'PAUSED_BY_BUDGET', 'PAUSED_BY_PROVIDER', 'PAUSED_BY_QUEUE')) AS backfills_active,
                (SELECT COALESCE(sum(byte_len), 0)::bigint FROM solprint.de_evidence WHERE raw_json IS NOT NULL) AS evidence_bytes,
                (SELECT count(*) FROM solprint.de_evidence WHERE raw_json IS NULL) AS evidence_pruned,
                (SELECT max(decoded_at) FROM solprint.de_transactions) AS last_decoded",
        )
        .fetch_one(self.pool())
        .await
        .map_err(|x| e(&x))?;
        Ok(DeCounts {
            jobs_by_state,
            oldest_pending_job_at: opt_utc(r.get("oldest_pending")),
            transactions: r.get("txs"),
            transactions_by_finality,
            transactions_by_status,
            swaps_canonical: r.get("swaps_canonical"),
            swaps_verified: r.get("swaps_verified"),
            swaps_retracted: r.get("swaps_retracted"),
            swaps_by_protocol,
            open_issues_by_severity,
            outbox_events: r.get("outbox_events"),
            outbox_undelivered: r.get("outbox_undelivered"),
            targets_enabled: r.get("targets_enabled"),
            targets_total: r.get("targets_total"),
            backfills_active: r.get("backfills_active"),
            evidence_bytes: r.get("evidence_bytes"),
            evidence_pruned: r.get("evidence_pruned"),
            last_decoded_at: opt_utc(r.get("last_decoded")),
        })
    }

