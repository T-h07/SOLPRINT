#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PersistOutcome {
    Applied {
        revision: i32,
    },
    /// Same evidence hash and decoder version: nothing rewritten.
    Unchanged {
        revision: i32,
    },
    /// Another writer changed the transaction since `StoredTxState` was read.
    Conflict,
    /// The job lease was lost (expired and re-claimed): nothing written.
    LeaseLost,
}

/// Finality strength for the non-regression rule.
#[must_use]
pub fn finality_rank(f: &str) -> u8 {
    match f {
        "OBSERVED_PROCESSED" => 1,
        "OBSERVED_CONFIRMED" | "FINALITY_UNKNOWN" | "POSSIBLY_ORPHANED" => 2,
        "FINALIZED" | "ORPHANED" => 3,
        _ => 0,
    }
}

