//! DATA ENGINE persistence (`migrations/20261127000003_data_engine.sql`).
//!
//! Row and write types are plain data; `solprint-data-engine` maps its domain
//! model onto them. Unsigned 64-bit quantities travel as decimal strings and
//! are bound with `::numeric` (read back with `::text`): PostgreSQL BIGINT is
//! signed and cannot hold the full u64 range.
//!
//! Invariants enforced here:
//! * one durable job per signature; claiming uses `FOR UPDATE SKIP LOCKED`
//!   and a lease, and no database transaction is held while fetching;
//! * evidence, derived records, quality issues, outbox events and the job's
//!   completion commit in **one** transaction (`de_persist_transaction`);
//! * reprocessing revises records in place (deterministic ids) and retracts
//!   records that no longer exist, never duplicating them;
//! * finality never regresses; a transaction leaves `FINALIZED`/`ORPHANED`
//!   only through an explicit orphan transition.

