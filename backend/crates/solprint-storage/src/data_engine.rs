async fn complete(
    tx: &mut Transaction<'_, Postgres>,
    job_id: i64,
    revision: i32,
) -> Result<(), StorageError> {
    sqlx::query(
        "UPDATE solprint.de_jobs SET state = 'COMPLETED', lease_owner = NULL, lease_expires_at = NULL,
                last_error_code = NULL, result_revision = $2, completed_at = now(), updated_at = now()
          WHERE job_id = $1",
    )
    .bind(job_id)
    .bind(revision)
    .execute(&mut **tx)
    .await
    .map_err(|x| e(&x))?;
    Ok(())
}

/// Merge two finality states; the stronger one wins (no regression).
#[must_use]
pub fn merge_finality<'a>(current: Option<&'a str>, new: &'a str) -> &'a str {
    match current {
        Some(c) if finality_rank(c) > finality_rank(new) => c,
        Some(c)
            if finality_rank(c) == finality_rank(new)
                && c != "FINALITY_UNKNOWN"
                && c != "POSSIBLY_ORPHANED" =>
        {
            c
        }
        _ => new,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finality_never_regresses() {
        assert_eq!(
            merge_finality(Some("FINALIZED"), "OBSERVED_CONFIRMED"),
            "FINALIZED"
        );
        assert_eq!(
            merge_finality(Some("OBSERVED_CONFIRMED"), "FINALIZED"),
            "FINALIZED"
        );
        assert_eq!(
            merge_finality(None, "OBSERVED_CONFIRMED"),
            "OBSERVED_CONFIRMED"
        );
        assert_eq!(
            merge_finality(Some("FINALITY_UNKNOWN"), "OBSERVED_CONFIRMED"),
            "OBSERVED_CONFIRMED"
        );
        assert_eq!(
            merge_finality(Some("ORPHANED"), "OBSERVED_CONFIRMED"),
            "ORPHANED"
        );
    }
}
